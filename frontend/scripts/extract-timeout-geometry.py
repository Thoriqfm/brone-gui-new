"""Extract exact timeout SVG controls; does not modify original artwork."""
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET

root = Path(__file__).resolve().parents[1]
assets = root / "public/assets/face-layers"

def commands(d):
    tokens = re.findall(r"[A-Za-z]|[-+]?(?:\d*\.\d+|\d+\.?\d*)(?:[eE][-+]?\d+)?", d)
    result = []
    while tokens:
        tag = tokens.pop(0)
        assert tag in ("M", "C", "Z")
        count = {"M": 2, "C": 6, "Z": 0}[tag]
        result.append([tag] + [float(tokens.pop(0)) for _ in range(count)])
    return result

def node(element):
    tag = element.tag.split("}")[-1]
    attrs = {}
    for key, value in element.attrib.items():
        if key == "d":
            continue
        key = re.sub(r"-([a-z])", lambda m: m[1].upper(), key)
        if key in "cx cy r strokeWidth x1 y1 x2 y2 offset".split():
            value = float(value)
        elif value.startswith("url(#"):
            value = {"ref": value[5:-1]}
        elif key == "transform":
            # A circle is unchanged by rotation about its own center.
            assert tag == "circle" and value.startswith("rotate(180 ")
            continue
        attrs[key] = value
    if tag == "circle":
        tag = "ellipse"
        attrs["rx"] = attrs["ry"] = attrs.pop("r")
    result = {"tag": tag, "attributes": attrs, "children": [node(c) for c in element]}
    if tag == "path":
        result["commands"] = commands(element.get("d"))
    return result

eyes = {}
for side in ("left", "right"):
    svg = ET.parse(assets / f"eyes/{side}/timeout-eye-{side}.svg").getroot()
    eyes[side] = {"kind": "layered", "side": side, "width": 160, "height": 162, "layers": [node(c) for c in svg]}
text = '// Generated by scripts/extract-timeout-geometry.py; exact source controls.\nimport type { LayeredEyeGeometry } from "./types";\n'
text += "export const TIMEOUT_EYES = " + json.dumps(eyes, separators=(",", ":")) + ' as const satisfies Record<"left" | "right", LayeredEyeGeometry>;\n'
(root / "src/geometry/eyes/timeoutSource.ts").write_text(text)

path = ET.parse(assets / "mouth/timeout-mouth.svg").getroot()[0]
cs = commands(path.get("d"))
point = lambda x, y: [x / 253, y / 45]
contour = {"start": point(*cs[0][1:]), "curves": [[point(*c[i:i+2]) for i in (1, 3, 5)] for c in cs[1:-1]]}
mouth = {"width": 253, "height": 45, "strokeWidth": 5, "cavityStrokeWidth": 5, "cavity": contour, "tongue": None}
text = '// Generated by scripts/extract-timeout-geometry.py; exact normalized source controls.\nimport type { MouthGeometry } from "./types";\n'
text += "export const TIMEOUT_MOUTH: MouthGeometry = " + json.dumps(mouth, separators=(",", ":")) + ";\n"
(root / "src/geometry/mouth/timeoutSource.ts").write_text(text)
print("Extracted exact timeout eyes and mouth; original SVGs untouched.")
