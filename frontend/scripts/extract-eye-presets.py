"""Rebuild measured TypeScript data from original, hash-verified SVGs. No fitting."""
import hashlib
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET

inventory = json.loads(Path('reports/eye-svg-inventory.json').read_text(encoding='utf-8-sig'))
numeric = set('cx cy rx ry x y width height x1 y1 x2 y2 strokeWidth opacity fillOpacity offset floodOpacity dy stdDeviation k2 k3'.split())


def commands(path):
    tokens = re.findall(r'[A-Za-z]|[-+]?(?:\d*\.\d+|\d+\.?\d*)(?:[eE][-+]?\d+)?', path)
    result = []
    while tokens:
        command = tokens.pop(0)
        assert command in ['M', 'L', 'C', 'Z'], command
        count = 0 if command == 'Z' else 6 if command == 'C' else 2
        result.append([command] + [float(tokens.pop(0)) for _ in range(count)])
    return result


def convert(element):
    attributes = {}
    path_commands = None
    for key, value in element.attrib.items():
        key = 'xlinkHref' if key == '{http://www.w3.org/1999/xlink}href' else re.sub(r'-([a-z])', lambda m: m[1].upper(), key)
        if key == 'd':
            path_commands = commands(value)
            continue
        if key in numeric:
            value = float(value)
        elif value.startswith('url(#'):
            assert value.endswith(')')
            value = {'ref': value[5:-1]}
        elif key == 'xlinkHref':
            assert value.startswith('#')
            value = {'ref': value[1:]}
        elif key == 'values':
            value = [float(v) for v in value.split()]
        elif key == 'transform':
            match = re.fullmatch(r'(matrix|rotate)\(([^)]+)\)', value)
            assert match, value
            value = {'kind': match[1], 'values': [float(v) for v in match[2].split()]}
        attributes[key] = value
    result = {'tag': element.tag.split('}')[-1], 'attributes': attributes,
              'children': [convert(child) for child in element]}
    if path_commands is not None:
        result['commands'] = path_commands
    return result


def format_node(node, indent):
    prefix = ' ' * indent
    lines = [prefix + '{ tag: ' + json.dumps(node['tag']) + ', attributes: ' + json.dumps(node['attributes']) + ',']
    if 'commands' in node:
        lines.append(prefix + '  commands: [')
        lines.extend(prefix + '    ' + json.dumps(command) + ',' for command in node['commands'])
        lines.append(prefix + '  ],')
    if node['children']:
        lines.append(prefix + '  children: [')
        lines.extend(format_node(child, indent + 4) + ',' for child in node['children'])
        lines.append(prefix + '  ] }')
    else:
        lines.append(prefix + '  children: [] }')
    return '\n'.join(lines)


lines = ['// Generated by scripts/extract-eye-presets.py from hash-verified approved SVGs.',
         '// Native coordinates and document order; no simplification or path fitting.',
         'import type { LayeredEyeGeometry } from "./types";',
         'export const SOURCE_EYE_PRESETS = {']
for item in inventory:
    path = Path(item['file'])
    assert hashlib.sha256(path.read_bytes()).hexdigest() == item['sha256'], path
    if item['expression'] in ['idle', 'shock']:
        continue
    root = ET.parse(path).getroot()
    assert set(root.attrib) == {'width', 'height', 'viewBox', 'fill'}
    assert root.get('fill') == 'none'
    assert root.get('viewBox') == f'0 0 {root.get("width")} {root.get("height")}'
    name = item['expression'].upper().replace('-', '_') + '_' + item['side'].upper()
    lines.append(f'  {name}: {{ kind: "layered", side: "{item["side"]}", width: {root.get("width")}, height: {root.get("height")}, layers: [')
    lines.extend(format_node(convert(child), 4) + ',' for child in root)
    lines.append('  ] },')
lines.append('} as const satisfies Record<string, LayeredEyeGeometry>;')
Path('src/geometry/eyes/sourcePresets.ts').write_text('\n'.join(lines) + '\n', encoding='utf-8')
print('Extracted 10 independently measured eye scenes from verified originals.')
